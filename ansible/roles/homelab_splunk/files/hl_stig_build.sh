#!/bin/bash
# Builds the content of the role's STIG audit rules file (spec 5.3 audit_rules; run by the role
# on the target host, as root).
#   hl_stig_build.sh <stig rules file> <privileged rules file> <arches, comma separated>
# Prints the rules on stdout, and the facts about the build as HL_* lines. Rule lines start with
# "-" and comments with "##", which is how audit_rules.yml tells them from anything else.
#   - STIG sample: only the rule lines, so no -D/-b/-f/-e (the stock audit.rules keeps its own).
#   - Each -S list is filtered per ABI with ausyscall, because auditctl aborts the whole load on a
#     name the ABI doesn't have (aarch64 has no chmod, chown, lchown, open, creat, rename, unlink).
#   - Privileged commands: the file's "#find ..." / "#filecap ..." comments (one hash) are the
#     generators. They only write b64, so b32 forms are added here when b32 is asked for.
#   - No privileged rules on a host with setuid binaries means the generators broke: exit 3.
set -euo pipefail
export LC_ALL=C

stig_src=$1
priv_src=$2
arches=$3

fail() {
    echo "HL_ERROR=$2"
    exit "$1"
}

has_arch() {
    case ",$arches," in
    *",$1,"*) return 0 ;;
    *) return 1 ;;
    esac
}

[ -f "$stig_src" ] || fail 2 "missing $stig_src (package audit-rules)"

machine=$(uname -m)
abi_b32=
case "$machine" in
aarch64) abi_b32=arm ;;
x86_64) abi_b32=i386 ;;
esac
if has_arch b32 && [ -z "$abi_b32" ]; then
    fail 2 "no 32-bit ABI known for $machine: set hl_audit_arches"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

dropped=()
dropped_rules=()
rules=()

# Sets filtered_rule to the rule without the syscall names its ABI doesn't have, or to nothing
# when a -S list loses every name.
filter_rule() {
    local rule=$1 arch=b64 abi tok kept n i=0 had_s=0 kept_s=0 out=
    local -a toks names
    if [[ $rule =~ -F[[:space:]]+arch=(b32|b64) ]]; then
        arch=${BASH_REMATCH[1]}
    fi
    if [ "$arch" = b32 ]; then abi=$abi_b32; else abi=$machine; fi
    read -r -a toks <<<"$rule"
    while [ "$i" -lt "${#toks[@]}" ]; do
        tok=${toks[i]}
        if [ "$tok" = -S ] && [ $((i + 1)) -lt "${#toks[@]}" ]; then
            had_s=1
            kept=
            IFS=, read -r -a names <<<"${toks[i + 1]}"
            for n in "${names[@]}"; do
                if [[ $n == all || $n =~ ^[0-9]+$ ]] || ausyscall "$abi" "$n" --exact >/dev/null 2>&1; then
                    kept+="${kept:+,}$n"
                else
                    dropped+=("$arch/$abi:$n")
                fi
            done
            if [ -n "$kept" ]; then
                out+="${out:+ }-S $kept"
                kept_s=1
            fi
            i=$((i + 2))
        else
            out+="${out:+ }$tok"
            i=$((i + 1))
        fi
    done
    if [ "$had_s" -eq 1 ] && [ "$kept_s" -eq 0 ]; then
        dropped_rules+=("$rule")
        filtered_rule=
    else
        filtered_rule=$out
    fi
}

# --- The STIG sample ---
while IFS= read -r line || [ -n "$line" ]; do
    line=${line#"${line%%[![:space:]]*}"}
    case "$line" in
    -a* | -A* | -w*) ;;
    *) continue ;;
    esac
    if [[ $line =~ -F[[:space:]]+arch=(b32|b64) ]] && ! has_arch "${BASH_REMATCH[1]}"; then
        continue
    fi
    filter_rule "$line"
    if [ -n "$filtered_rule" ]; then
        rules+=("$filtered_rule")
    fi
done <"$stig_src"

# --- The privileged-command rules ---
if [ -f "$priv_src" ]; then
    sed -n -E 's/^#((find|filecap)[[:space:]].*)$/\1/p' "$priv_src" >"$tmp/gen.sh"
    (cd "$tmp" && bash gen.sh 2>/dev/null) || true
fi

priv=()
if [ -s "$tmp/priv.rules" ]; then
    while IFS= read -r line; do
        if has_arch b64; then priv+=("$line"); fi
        if has_arch b32; then priv+=("${line/-F arch=b64/-F arch=b32}"); fi
    done < <(sort -u "$tmp/priv.rules")
fi

setuid=$(find /bin /sbin /usr/bin /usr/sbin -type f -perm -04000 2>/dev/null | wc -l || true)
if [ "${#priv[@]}" -eq 0 ] && [ "$setuid" -gt 0 ]; then
    fail 3 "no privileged rules generated from $priv_src, but this host has $setuid setuid binaries"
fi

echo "## Managed by the homelab_splunk role (audit_rules); removed by audit_rules_remove."
echo "## STIG sample rules from $stig_src, then the privileged-command rules generated by the"
echo "## commands in $priv_src. No -D/-b/-f/-e: audit.rules keeps its own."
printf '%s\n' "${rules[@]}"
if [ "${#priv[@]}" -gt 0 ]; then
    echo "## Privileged commands"
    printf '%s\n' "${priv[@]}" | sort -u
fi

joined() {
    if [ "$#" -eq 0 ]; then
        echo none
    else
        printf '%s\n' "$@" | sort -u | paste -sd, -
    fi
}
echo "HL_STIG_LINES=${#rules[@]}"
echo "HL_PRIV=${#priv[@]}"
echo "HL_SETUID=$setuid"
echo "HL_DROPPED=$(joined "${dropped[@]}")"
echo "HL_DROPPED_RULES=$(joined "${dropped_rules[@]}")"
